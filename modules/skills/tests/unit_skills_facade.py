"""Composition-root tests: one per authoring facade wrapper."""

from __future__ import annotations

from pathlib import Path

from modules.skills.src.root_skills_container import SkillsFacade
from modules.skills.tests.fixture_skills import crafted_tree


def _facade(root: Path) -> SkillsFacade:
    return SkillsFacade(default_root=root)


def test_facade_validate(tmp_path: Path) -> None:
    result = _facade(crafted_tree(tmp_path)).validate()
    assert result.report is not None
    assert result.report.issue_count == 1


def test_facade_catalog_rebuild_and_check(tmp_path: Path) -> None:
    facade = _facade(crafted_tree(tmp_path))
    rebuilt = facade.catalog_rebuild()
    assert rebuilt.catalog is not None
    assert rebuilt.catalog.skills == 2

    checked = facade.catalog_check()
    assert checked.check is not None
    assert checked.check.in_sync


def test_facade_discover(tmp_path: Path) -> None:
    facade = _facade(crafted_tree(tmp_path))
    facade.catalog_rebuild()
    result = facade.discover("docs")
    assert [match.skill for match in result.matches] == ["doc-drafts"]


def test_facade_weed(tmp_path: Path) -> None:
    result = _facade(crafted_tree(tmp_path)).weed()
    assert result.plan is not None
    assert result.plan.lines == ()


def test_facade_repair_dry_run_then_apply(tmp_path: Path) -> None:
    facade = _facade(crafted_tree(tmp_path))
    preview = facade.repair()
    assert preview.outcome is None

    applied = facade.repair(apply=True)
    assert applied.outcome is not None


def test_facade_move_and_archive(tmp_path: Path) -> None:
    root = crafted_tree(tmp_path)
    facade = _facade(root)

    moved = facade.move("drafts/doc-drafts", "notes", apply=True)
    assert moved.outcome is not None

    archived = facade.archive("notes/note-taker", apply=True)
    assert archived.outcome is not None
    assert (root / "_archive" / "notes" / "note-taker").exists()


def test_facade_new_category(tmp_path: Path) -> None:
    root = crafted_tree(tmp_path)
    result = _facade(root).new_category("beta-cat", "Second", apply=True)
    assert result.new_category is not None
    assert result.new_category.created
    assert (root / "beta-cat" / "DESCRIPTION.md").exists()


def test_facade_merge_plan_is_read_only(tmp_path: Path) -> None:
    root = crafted_tree(tmp_path)
    result = _facade(root).merge_plan("drafts/doc-drafts", "notes/note-taker")
    assert result.merge is not None
    assert result.lines
    assert (root / "drafts" / "doc-drafts").exists()


def test_facade_rules(tmp_path: Path) -> None:
    document = _facade(crafted_tree(tmp_path)).rules(markdown=True)
    assert document.document is not None
    assert document.document.startswith("<!-- Generated by `aa skills rules")
