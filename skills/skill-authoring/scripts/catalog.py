"""Catalog rendering and the drift check (design §6.1, risk R7/G4).

Owns everything that turns the live tree into a ``CATALOG.md``: the
rendering (``write_catalog``/``rebuild_catalog``), the catalog reader
that ``discover`` scores against (``load_catalog_skill_rows``), and
``catalog --check`` — regenerate to a temp file and diff against the
tracked artifact, exit 3 on drift. The tree walks themselves live in
``model.py``; this module only renders and compares.

``rebuild_catalog`` writes the path the caller passes, so the mutating
commands can rewrite the real catalog under ``--apply`` while the drift
check writes a throwaway copy.
"""

from __future__ import annotations

import difflib
import tempfile
from pathlib import Path

import model
from skill_rules import md_escape

__all__ = [
    "CATALOG_FILENAME",
    "catalog_cell_problems",
    "catalog_path",
    "check_catalog",
    "load_catalog_skill_rows",
    "read_catalog_text",
    "rebuild_catalog",
    "render_catalog",
    "write_catalog",
]

CATALOG_FILENAME = "CATALOG.md"

#: The catalog header names the regeneration command. Kept in sync with the
#: tracked CATALOG.md: a rebuild must emit the same line the tracked artifact
#: carries, or ``catalog --check`` reports drift.
_HEADER = [
    "# Skills Catalog",
    "",
    "Generated by skill-librarian. Rebuild with `python3 skills/skill-authoring/scripts/cli.py catalog`.",
    "",
    "## Categories",
    "",
    "| Category | Description | Skills |",
    "|---|---|---|",
]


def catalog_path(skills_root: Path) -> Path:
    """The catalog file for a skills root."""
    return skills_root / CATALOG_FILENAME


def render_catalog(
    entries: list[model.SkillEntry],
    categories: list[model.CategorySummary],
) -> list[str]:
    """Render the catalog body: the Categories table then the Skills table.

    Verbatim from the original ``librarian.py`` ``write_catalog``: sort
    order, the ``(missing …)`` placeholders, and the pipe-escaping must
    not change, or a rebuild drifts the tracked artifact.
    """
    lines = list(_HEADER)

    for cat in sorted(categories, key=lambda item: item.category):
        description = cat.description or "(missing DESCRIPTION.md)"
        lines.append(
            f"| {md_escape(cat.category)} "
            f"| {md_escape(description)} "
            f"| {cat.skill_count} |"
        )

    lines.extend(
        [
            "",
            "## Skills",
            "",
            "| Skill Name | Category | Description | Path |",
            "|---|---|---|---|",
        ]
    )

    for entry in sorted(entries, key=lambda item: (item.category, item.skill)):
        description = entry.description or "(missing description)"
        lines.append(
            f"| {md_escape(entry.skill)} "
            f"| {md_escape(entry.category)} "
            f"| {md_escape(description)} "
            f"| {md_escape(entry.path)} |"
        )

    return lines


def write_catalog(
    entries: list[model.SkillEntry],
    categories: list[model.CategorySummary],
    path: Path,
) -> None:
    """Write the rendered catalog to ``path`` (trailing newline included)."""
    path.write_text("\n".join(render_catalog(entries, categories)) + "\n", encoding="utf-8")


def rebuild_catalog(skills_root: Path, path: Path | None = None) -> tuple[
    list[model.SkillEntry], list[model.CategorySummary]
]:
    """Walk the tree and write ``path`` (the catalog by default).

    Returns the rows the render used, so callers can report counts or
    chain into another read without walking twice.
    """
    entries = model.skill_entries(skills_root)
    categories = model.category_summaries(entries, skills_root)
    write_catalog(entries, categories, path if path is not None else catalog_path(skills_root))
    return entries, categories


def read_catalog_text(path: Path) -> str:
    """Read the catalog with the same codec the original parser used."""
    return path.read_text(encoding="utf-8-sig", errors="replace")


def _cell_round_trips(cell: str) -> bool:
    """True if ``cell`` survives the catalog escape→unescape round-trip.

    ``md_escape`` writes pipes as ``&#124;`` and ``load_catalog_skill_rows``
    reads them back, so ``a|b`` round-trips losslessly. A cell that already
    contains the literal text ``&#124;`` or a newline would be read back as
    ``|`` or a space — silently corrupting the index. Those cells fail closed
    here so ``catalog --check`` reports drift instead of emitting a broken row.
    """
    return md_escape(cell).replace("&#124;", "|") == cell


def catalog_cell_problems(
    entries: list[model.SkillEntry], categories: list[model.CategorySummary]
) -> list[str]:
    """Return a human-readable line per catalog cell that does not round-trip.

    A cell that does not round-trip means the rendered catalog cannot be
    parsed back into the same value, so the artifact would silently lie about
    the tree. Fail-closed: any problem here is drift.
    """
    problems: list[str] = []
    for cat in categories:
        for field, value in (("category", cat.category), ("description", cat.description)):
            if value and not _cell_round_trips(value):
                problems.append(f"category {cat.category!r}:{field} = {value!r}")

    for entry in entries:
        for field in ("skill", "category", "description", "path"):
            value = getattr(entry, field)
            if value and not _cell_round_trips(value):
                problems.append(f"skill {entry.path!r}:{field} = {value!r}")

    return problems


def load_catalog_skill_rows(skills_root: Path) -> list[dict[str, str]]:
    """Parse the ``## Skills`` table into ``{skill, category, description, path}``.

    Verbatim semantics from the original ``librarian.py``: a missing
    catalog is regenerated, the ``## Skills`` section ends at the next
    ``## `` heading, separator rows are skipped, pipes are un-escaped, and
    a parse that yields nothing falls back to the live tree (the silent
    fallback is PR-5's drift-signal work — kept faithful here).
    """
    path = catalog_path(skills_root)
    if not path.exists():
        rebuild_catalog(skills_root)

    text = read_catalog_text(path)
    entries: list[dict[str, str]] = []
    in_skills = False

    for line in text.splitlines():
        stripped = line.strip()

        if stripped == "## Skills":
            in_skills = True
            continue

        if in_skills and stripped.startswith("## "):
            break

        if not in_skills:
            continue

        if not stripped.startswith("|"):
            continue

        if stripped.startswith("| Skill Name"):
            continue

        if set(stripped.replace("|", "").strip()) <= {"-", " "}:
            continue

        cells = [
            cell.strip().replace("&#124;", "|")
            for cell in stripped.strip("|").split("|")
        ]

        if len(cells) >= 4:
            entries.append(
                {
                    "skill": cells[0],
                    "category": cells[1],
                    "description": cells[2],
                    "path": cells[3],
                }
            )

    if not entries:
        entries = [
            {
                "skill": entry.skill,
                "category": entry.category,
                "description": entry.description,
                "path": entry.path,
            }
            for entry in model.skill_entries(skills_root)
        ]

    return entries


def check_catalog(skills_root: Path) -> tuple[bool, str, list[str]]:
    """Regenerate the catalog to a temp file and diff against the tracked one.

    Returns ``(in_sync, summary, diff_lines)``: ``in_sync`` is False and
    ``summary`` explains the drift when the tracked artifact does not match
    what the live tree renders. ``diff_lines`` is a unified diff (empty when
    in sync) a caller can print or log. Read-only: the tracked file is
    never touched.
    """
    path = catalog_path(skills_root)

    if not path.exists():
        return (
            False,
            f"Catalog missing: {path} (rebuild with the catalog subcommand)",
            [],
        )

    with tempfile.TemporaryDirectory(prefix="catalog-check-") as tmp:
        candidate = Path(tmp) / CATALOG_FILENAME
        entries, categories = rebuild_catalog(skills_root, candidate)
        current = read_catalog_text(path).splitlines()
        regenerated = read_catalog_text(candidate).splitlines()

    diff_lines = list(
        difflib.unified_diff(
            current,
            regenerated,
            fromfile=str(path),
            tofile=f"regenerated ({path})",
            lineterm="",
        )
    )

    if diff_lines:
        message = (
            f"Catalog drift detected: {path} does not match the live tree "
            f"({len(diff_lines)} diff line(s)); rebuild with the catalog subcommand"
        )
        return False, message, diff_lines

    # Fail-closed escaping assertion (§9.2): no rendered cell may survive the
    # escape→unescape round-trip lossily, or a crafted description silently
    # corrupts the index.
    cell_problems = catalog_cell_problems(entries, categories)
    if cell_problems:
        detail = "; ".join(cell_problems)
        message = (
            f"Catalog drift detected: {path} contains cells that do not round-trip "
            f"through the catalog parser ({len(cell_problems)} cell(s)): {detail}"
        )
        return False, message, [f"drift: {p}" for p in cell_problems]

    return True, f"Catalog in sync: {path}", []
