"""Markdown rendering of the SSOT rules (design §5.3, §6.1).

``cli rules --markdown`` prints the human-readable rendering of
``_rules/skill_rules.py``: one section per ``Rule``, whose body is the
verbatim message template the validator emits, plus the loader citation
when one exists. The rendering reads the taxonomy — it contains no rule
text of its own — so the generated ``_rules/skill-rules.md`` cannot
disagree with the executable rules (risk R7).

Regenerate the committed artifact with::

    python3 skills/skill-authoring/scripts/cli.py rules --markdown \\
        > skills/skill-authoring/_rules/skill-rules.md
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_RULES_DIR = Path(__file__).resolve().parent.parent / "_rules"
if str(_RULES_DIR) not in sys.path:
    sys.path.insert(0, str(_RULES_DIR))

from skill_rules import RULES, Rule

__all__ = ["render_rules_markdown", "render_rules_summary"]

_DOCS_HEADER = """\
<!-- Generated by `cli rules --markdown` — do not edit by hand.
     The generator is skills/skill-authoring/scripts/docs.py; the rules it
     renders live in skills/skill-authoring/_rules/skill_rules.py. The
     committed file must be byte-identical to the generator's output, or
     the doc has drifted from the executable rules (design risk R7). -->

# Skill rules

What `skills/skill-authoring` enforces a skill tree against. Every rule
below is emitted by the validator — `python3
skills/skill-authoring/scripts/cli.py validate` — so this page cannot state
a constraint the checker does not enforce, and the checker cannot enforce a
constraint this page does not state. Provenance for each rule (the loader
file it was first read from, or the failure mode that motivated it) lives
in `RULES.md`, next to this file.

- **Rules:** {rule_count}
- **Levels:** `error` (a rule violation fails the skill or category it hits)
- **SSOT:** `_rules/skill_rules.py` — `NAME_RE`, `MAX_DESCRIPTION_LEN`, and
  `issue_message()` read their constants from there.
"""

#: What each message template's interpolated field means, for readers of
#: the rendered doc who do not read the checker.
_FIELD_HELP = {
    "name": "the skill's frontmatter name",
    "dir": "the skill's directory name",
    "length": "the offending length in characters",
    "max_len": "the enforced maximum",
    "paths": "every location the violation was found at",
}


def _format_fields(detail: str) -> str:
    """The template's ``{}`` placeholders, as the doc's readers see them.

    The validator binds them by keyword at its callsites; the rendered doc
    names the fields so a reader can predict the message shape without
    reading the checker.
    """
    fields = re.findall(r"\{([A-Za-z_][A-Za-z0-9_]*)\}", detail)
    if not fields:
        return "constant message"
    ordered = sorted(set(fields))
    return ", ".join(f"`{name}` ({_FIELD_HELP[name]})" for name in ordered)


def _rule_section(rule_obj: Rule) -> list[str]:
    """One rule = one `###` section; the detail is the verbatim message."""
    lines = [
        f"### `{rule_obj.id}` — {rule_obj.summary}",
        "",
        f"- **Rule ID:** `{rule_obj.id}`",
        f"- **Level:** `{rule_obj.level.value}`",
        f"- **Issue type:** `{rule_obj.issue.value}` (the string `validate` prints)",
        f"- **Fields:** {_format_fields(rule_obj.detail_md)}",
        "",
        "**Message (verbatim from `ISSUE_MESSAGES`):**",
        "",
        f"> {rule_obj.detail_md}",
    ]

    if rule_obj.why:
        lines.extend(["", f"**Provenance:** {rule_obj.why}"])

    lines.append("")
    return lines


def render_rules_markdown() -> str:
    """The full rules document.

    Byte-stable: the output depends only on ``skill_rules``, so a clean
    checkout always renders the committed file identically (the round-trip
    test pins this).
    """
    lines = [_DOCS_HEADER.format(rule_count=len(RULES)), "## Rules", ""]

    for rule_obj in RULES:
        lines.extend(_rule_section(rule_obj))

    # Byte-stable tail: exactly one trailing newline, so a shell redirect
    # (`> _rules/skill-rules.md`) reproduces the committed file exactly.
    return "\n".join(lines).rstrip("\n") + "\n"


def render_rules_summary() -> str:
    """The compact one-line-per-rule form `cli rules` prints."""
    lines = [f"{len(RULES)} rules from _rules/skill_rules.py:", ""]
    for rule_obj in RULES:
        lines.append(f"- [{rule_obj.level.value}] {rule_obj.id} — {rule_obj.summary}")
    return "\n".join(lines)
