#!/usr/bin/env python3
"""Skill Librarian: maintain CATALOG.md, category descriptions, and library moves."""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    yaml = None

SCRIPT = Path(__file__).resolve()

if len(SCRIPT.parents) < 4:
    print(
        "ERROR: skill-librarian must be installed as "
        "<skills-root>/<category>/<skill>/scripts/librarian.py",
        file=sys.stderr,
    )
    sys.exit(1)

# Expected layout: <skills-root>/<category>/<skill>/scripts/librarian.py
SKILLS_ROOT = SCRIPT.parents[3]
CATALOG_PATH = SKILLS_ROOT / "CATALOG.md"
ARCHIVE_ROOT = SKILLS_ROOT / "_archive"
CATEGORY_DESCRIPTION_FILENAME = "DESCRIPTION.md"
IGNORED_CATEGORY_DIRS = {".git", ".hg", ".svn", "__pycache__", "_archive"}
NAME_RE = re.compile(r"^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$")
MAX_DESCRIPTION_LEN = 1024


def fail(message: str) -> None:
    print(f"ERROR: {message}", file=sys.stderr)
    sys.exit(1)


def relpath(path: Path) -> str:
    try:
        return str(path.relative_to(SKILLS_ROOT))
    except ValueError:
        return str(path)


def clean_one_line(value: object) -> str:
    return " ".join(str(value).split()).strip()


def yaml_quote(value: object) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def md_escape(value: object) -> str:
    return str(value).replace("|", "&#124;").replace("\n", " ").strip()


def parse_frontmatter(path: Path) -> dict:
    try:
        text = path.read_text(encoding="utf-8-sig", errors="replace")
    except OSError:
        return {}

    stripped = text.lstrip()
    if not stripped.startswith("---"):
        return {}

    parts = stripped.split("---", 2)
    if len(parts) < 3:
        return {}

    fm_text = parts[1]

    if yaml is not None:
        try:
            data = yaml.safe_load(fm_text)
            if isinstance(data, dict):
                return data
        except Exception:
            pass

    data = {}
    for line in fm_text.splitlines():
        if not line.strip():
            continue
        if line != line.lstrip():
            continue
        if ":" not in line:
            continue

        key, value = line.split(":", 1)
        key = key.strip()
        value = value.strip()

        if not key or value in {"", "|", ">", "|-", ">-"}:
            continue
        if value.startswith(("[", "{", "- ")):
            continue

        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"\"", "'"}:
            value = value[1:-1]

        data[key] = value

    return data


def category_dirs():
    if not SKILLS_ROOT.is_dir():
        fail(f"Skills root does not exist: {SKILLS_ROOT}")

    for path in sorted(SKILLS_ROOT.iterdir()):
        if not path.is_dir():
            continue
        if path.name.startswith("."):
            continue
        if path.name in IGNORED_CATEGORY_DIRS:
            continue
        yield path


def skill_entries():
    entries = []

    for category in category_dirs():
        for skill_md in sorted(category.glob("*/SKILL.md")):
            skill_dir = skill_md.parent
            fm = parse_frontmatter(skill_md)

            entries.append(
                {
                    "skill": skill_dir.name,
                    "frontmatter_name": clean_one_line(fm.get("name", skill_dir.name)),
                    "category": category.name,
                    "description": clean_one_line(fm.get("description", "")),
                    "path": f"{category.name}/{skill_dir.name}",
                }
            )

    return entries


def category_summaries(entries):
    summaries = []

    for category in category_dirs():
        desc_file = category / CATEGORY_DESCRIPTION_FILENAME
        description = ""
        exists = desc_file.exists()

        if exists:
            fm = parse_frontmatter(desc_file)
            description = clean_one_line(fm.get("description", ""))

        skill_count = sum(1 for entry in entries if entry["category"] == category.name)

        summaries.append(
            {
                "category": category.name,
                "description": description,
                "description_file_exists": exists,
                "skill_count": skill_count,
            }
        )

    return summaries


def write_catalog(entries, categories):
    lines = [
        "# Skills Catalog",
        "",
        "Generated by skill-librarian. Rebuild with `librarian.py catalog`.",
        "",
        "## Categories",
        "",
        "| Category | Description | Skills |",
        "|---|---|---|",
    ]

    for cat in sorted(categories, key=lambda item: item["category"]):
        description = cat["description"] or "(missing DESCRIPTION.md)"
        lines.append(
            f"| {md_escape(cat['category'])} "
            f"| {md_escape(description)} "
            f"| {cat['skill_count']} |"
        )

    lines.extend(
        [
            "",
            "## Skills",
            "",
            "| Skill Name | Category | Description | Path |",
            "|---|---|---|---|",
        ]
    )

    for entry in sorted(entries, key=lambda item: (item["category"], item["skill"])):
        description = entry["description"] or "(missing description)"
        lines.append(
            f"| {md_escape(entry['skill'])} "
            f"| {md_escape(entry['category'])} "
            f"| {md_escape(description)} "
            f"| {md_escape(entry['path'])} |"
        )

    CATALOG_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def rebuild_catalog():
    entries = skill_entries()
    categories = category_summaries(entries)
    write_catalog(entries, categories)
    return entries, categories


def load_catalog_skill_rows():
    if not CATALOG_PATH.exists():
        rebuild_catalog()

    text = CATALOG_PATH.read_text(encoding="utf-8-sig", errors="replace")
    entries = []
    in_skills = False

    for line in text.splitlines():
        stripped = line.strip()

        if stripped == "## Skills":
            in_skills = True
            continue

        if in_skills and stripped.startswith("## "):
            break

        if not in_skills:
            continue

        if not stripped.startswith("|"):
            continue

        if stripped.startswith("| Skill Name"):
            continue

        if set(stripped.replace("|", "").strip()) <= {"-", " "}:
            continue

        cells = [
            cell.strip().replace("&#124;", "|")
            for cell in stripped.strip("|").split("|")
        ]

        if len(cells) >= 4:
            entries.append(
                {
                    "skill": cells[0],
                    "category": cells[1],
                    "description": cells[2],
                    "path": cells[3],
                }
            )

    if not entries:
        entries = skill_entries()

    return entries


def iter_skill_md_files_relative(pattern: str):
    for path in SKILLS_ROOT.glob(pattern):
        try:
            rel = path.relative_to(SKILLS_ROOT)
        except ValueError:
            continue

        parts = rel.parts
        if not parts:
            continue

        if parts[0].startswith("."):
            continue

        if parts[0] in IGNORED_CATEGORY_DIRS:
            continue

        yield path


def make_issue(issue_type: str, message: str, path: str | None = None, category: str | None = None):
    issue = {"type": issue_type, "message": message}
    if path:
        issue["path"] = path
    if category:
        issue["category"] = category
    return issue


def validate_library():
    issues = []
    entries = skill_entries()
    categories = category_summaries(entries)

    for cat in categories:
        if not cat["description_file_exists"]:
            issues.append(
                make_issue(
                    "missing-category-description",
                    "DESCRIPTION.md is missing.",
                    category=cat["category"],
                )
            )
        elif not cat["description"]:
            issues.append(
                make_issue(
                    "empty-category-description",
                    "DESCRIPTION.md has no description.",
                    category=cat["category"],
                )
            )

        if cat["skill_count"] == 0:
            issues.append(
                make_issue(
                    "empty-category",
                    "Category has no skills.",
                    category=cat["category"],
                )
            )

    name_map = {}
    desc_map = {}

    for entry in entries:
        path = entry["path"]

        name_map.setdefault(entry["skill"], []).append(path)

        if entry["description"]:
            desc_map.setdefault(entry["description"], []).append(path)

        if entry["frontmatter_name"] != entry["skill"]:
            issues.append(
                make_issue(
                    "name-mismatch",
                    f"Frontmatter name '{entry['frontmatter_name']}' does not match directory '{entry['skill']}'.",
                    path=path,
                )
            )

        if (
            not NAME_RE.match(entry["skill"])
            or "--" in entry["skill"]
            or not (2 <= len(entry["skill"]) <= 64)
        ):
            issues.append(
                make_issue(
                    "invalid-skill-name",
                    "Directory name must be lowercase a-z, 0-9, hyphens, 2-64 chars, no leading/trailing hyphen or double hyphen.",
                    path=path,
                )
            )

        if not entry["description"]:
            issues.append(
                make_issue(
                    "missing-description",
                    "SKILL.md description is missing.",
                    path=path,
                )
            )
        else:
            if any(ch in entry["description"] for ch in "<>\""):
                issues.append(
                    make_issue(
                        "invalid-description-characters",
                        "Description contains <, >, or double quote characters.",
                        path=path,
                    )
                )

            if len(entry["description"]) > MAX_DESCRIPTION_LEN:
                issues.append(
                    make_issue(
                        "description-too-long",
                        f"Description is {len(entry['description'])} chars; max is {MAX_DESCRIPTION_LEN}.",
                        path=path,
                    )
                )

        skill_dir = SKILLS_ROOT / path
        nested = [
            str(p.relative_to(SKILLS_ROOT))
            for p in skill_dir.rglob("SKILL.md")
            if p != skill_dir / "SKILL.md"
        ]

        if nested:
            issues.append(
                make_issue(
                    "nested-skill-md",
                    f"Nested SKILL.md files found: {', '.join(nested)}",
                    path=path,
                )
            )

    for p in iter_skill_md_files_relative("*/SKILL.md"):
        issues.append(
            make_issue(
                "invalid-placement",
                "SKILL.md is directly under a category; expected category/skill/SKILL.md.",
                path=str(p.relative_to(SKILLS_ROOT)),
            )
        )

    for p in iter_skill_md_files_relative("*/*/*/SKILL.md"):
        issues.append(
            make_issue(
                "too-deep",
                "SKILL.md is nested deeper than category/skill/SKILL.md.",
                path=str(p.relative_to(SKILLS_ROOT)),
            )
        )

    for name, paths in sorted(name_map.items()):
        if len(paths) > 1:
            issues.append(
                make_issue(
                    "duplicate-skill-name",
                    f"Skill name '{name}' appears in: {', '.join(sorted(paths))}.",
                )
            )

    for description, paths in sorted(desc_map.items()):
        if len(paths) > 1:
            issues.append(
                make_issue(
                    "duplicate-description",
                    f"Identical description appears in: {', '.join(sorted(paths))}.",
                )
            )

    return {
        "skills_root": str(SKILLS_ROOT),
        "catalog": str(CATALOG_PATH),
        "issue_count": len(issues),
        "issues": issues,
    }


def write_category_description(category: Path, description: str, force: bool = False) -> bool:
    desc_file = category / CATEGORY_DESCRIPTION_FILENAME

    if desc_file.exists() and not force:
        return False

    desc_file.write_text(
        f"---\ndescription: {yaml_quote(description)}\n---\n",
        encoding="utf-8",
    )
    return True


def ensure_frontmatter_name(skill_md: Path, expected_name: str) -> bool:
    text = skill_md.read_text(encoding="utf-8-sig", errors="replace")
    stripped = text.lstrip()

    if not stripped.startswith("---"):
        new_text = f"---\nname: {expected_name}\ndescription: TODO\n---\n\n{text}"
        skill_md.write_text(new_text, encoding="utf-8")
        return True

    parts = stripped.split("---", 2)
    if len(parts) < 3:
        return False

    fm_lines = parts[1].splitlines()
    replaced = False

    for i, line in enumerate(fm_lines):
        if line.startswith("name:"):
            fm_lines[i] = f"name: {expected_name}"
            replaced = True
            break

    if not replaced:
        fm_lines.insert(0, f"name: {expected_name}")

    fm_body = "\n".join(fm_lines).strip("\n")
    body = parts[2]
    new_text = f"---\n{fm_body}\n---{body}"

    skill_md.write_text(new_text, encoding="utf-8")
    return True


def validate_category_name(name: str) -> None:
    if (
        not NAME_RE.match(name)
        or "--" in name
        or not (2 <= len(name) <= 64)
    ):
        fail(
            "Category name must be lowercase a-z, 0-9, hyphens, 2-64 chars, "
            "no leading/trailing hyphen or double hyphen."
        )


def resolve_skill_dir(skill_ref: str) -> Path:
    p = Path(skill_ref)
    candidates = []

    if p.is_absolute():
        candidates.append(p)
    else:
        if len(p.parts) == 2:
            candidates.append(SKILLS_ROOT / p)

        if len(p.parts) == 1:
            for category in category_dirs():
                candidates.append(category / p)

        candidates.append(Path.cwd() / p)
        candidates.append(SKILLS_ROOT / p)

    for candidate in candidates:
        candidate = Path(candidate).resolve()
        if candidate.is_dir() and (candidate / "SKILL.md").exists():
            return candidate

    fail(f"Could not find skill directory with SKILL.md: {skill_ref}")


def cmd_catalog(args) -> None:
    entries, categories = rebuild_catalog()
    print(f"Rebuilt {CATALOG_PATH}")
    print(f"Categories: {len(categories)}; skills: {len(entries)}")


def cmd_discover(args) -> None:
    tokens = [token.lower() for token in args.query.split() if token.strip()]
    if not tokens:
        fail("Query is empty")

    entries = load_catalog_skill_rows()
    scored = []

    for entry in entries:
        name = entry["skill"].lower()
        category = entry["category"].lower()
        description = entry["description"].lower()
        path = entry["path"].lower()

        score = 0

        for token in tokens:
            if token in name:
                score += 5
            if token in description:
                score += 3
            if token in category:
                score += 2
            if token in path:
                score += 1

        if score > 0:
            scored.append((score, entry))

    scored.sort(key=lambda item: item[0], reverse=True)
    top = scored[: args.limit]

    if not top:
        print("No matching skills found in CATALOG.md.")
        return

    print("| Skill | Category | Description | Path | Score |")
    print("|---|---|---|---|---|")

    for score, entry in top:
        print(
            f"| {md_escape(entry['skill'])} "
            f"| {md_escape(entry['category'])} "
            f"| {md_escape(entry['description'])} "
            f"| {md_escape(entry['path'])} "
            f"| {score} |"
        )


def cmd_validate(args) -> None:
    report = validate_library()

    if report["issue_count"] == 0:
        print("No validation issues found.")
        return

    print(f"{report['issue_count']} validation issue(s) found:")

    for issue in report["issues"]:
        locator = issue.get("path") or issue.get("category") or "library"
        print(f"- [{issue['type']}] {locator}: {issue['message']}")


def cmd_weed(args) -> None:
    entries = skill_entries()
    categories = category_summaries(entries)

    name_map = {}
    desc_map = {}

    for entry in entries:
        name_map.setdefault(entry["skill"], []).append(entry["path"])
        if entry["description"]:
            desc_map.setdefault(entry["description"], []).append(entry["path"])

    printed = False
    print("Weeding report:")

    for name, paths in sorted(name_map.items()):
        if len(paths) > 1:
            printed = True
            print(f"- duplicate-skill-name: '{name}' appears in: {', '.join(sorted(paths))}")

    for description, paths in sorted(desc_map.items()):
        if len(paths) > 1:
            printed = True
            short = description if len(description) <= 80 else description[:77] + "..."
            print(f"- duplicate-description: '{short}' appears in: {', '.join(sorted(paths))}")

    for cat in categories:
        if cat["skill_count"] == 0:
            printed = True
            print(f"- empty-category: {cat['category']}")

        if not cat["description_file_exists"]:
            printed = True
            print(f"- missing-category-description: {cat['category']}")

    if not printed:
        print("No obvious weeds found.")


def cmd_repair(args) -> None:
    repaired = []
    entries = skill_entries()

    for entry in entries:
        if entry["frontmatter_name"] != entry["skill"]:
            skill_md = SKILLS_ROOT / entry["path"] / "SKILL.md"
            if ensure_frontmatter_name(skill_md, entry["skill"]):
                repaired.append(f"Fixed name in {entry['path']}/SKILL.md")

    for category in category_dirs():
        desc_file = category / CATEGORY_DESCRIPTION_FILENAME
        if not desc_file.exists():
            write_category_description(category, f"Skills in the {category.name} category.")
            repaired.append(f"Created {category.name}/DESCRIPTION.md")

    rebuild_catalog()

    if repaired:
        print("Repairs applied:")
        for item in repaired:
            print(f"- {item}")
    else:
        print("No mechanical repairs needed.")

    print(f"Rebuilt {CATALOG_PATH}")


def cmd_move(args) -> None:
    source = resolve_skill_dir(args.skill)
    validate_category_name(args.target_category)

    target_category = SKILLS_ROOT / args.target_category

    if not target_category.is_dir():
        fail(
            f"Target category does not exist: {args.target_category}. "
            "Create it first with new-category."
        )

    dest = target_category / source.name

    if dest.exists():
        fail(f"Destination already exists: {relpath(dest)}")

    if source.parent == target_category:
        print(f"Skill already in category: {args.target_category}")
        return

    shutil.move(str(source), str(dest))
    rebuild_catalog()

    print(f"Moved {relpath(source)} -> {relpath(dest)}")
    print(f"Rebuilt {CATALOG_PATH}")


def cmd_new_category(args) -> None:
    validate_category_name(args.name)

    category = SKILLS_ROOT / args.name
    category.mkdir(exist_ok=True)

    description = args.description or f"Skills in the {args.name} category."
    wrote = write_category_description(category, description, force=args.force)

    rebuild_catalog()

    if wrote:
        print(f"Wrote {args.name}/DESCRIPTION.md")
    else:
        print(f"Kept existing {args.name}/DESCRIPTION.md; use --force to overwrite")

    print(f"Rebuilt {CATALOG_PATH}")


def cmd_archive(args) -> None:
    source = resolve_skill_dir(args.skill)
    category = source.parent.name
    dest = ARCHIVE_ROOT / category / source.name

    if dest.exists():
        fail(f"Archive destination already exists: {dest}")

    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(source), str(dest))

    archived_md = dest / "SKILL.md"
    if archived_md.exists():
        archived_md.rename(dest / "SKILL.md.archived")

    rebuild_catalog()

    print(f"Archived {relpath(source)} -> {relpath(dest)}")
    print(f"Rebuilt {CATALOG_PATH}")


def main() -> None:
    parser = argparse.ArgumentParser(
        prog="librarian.py",
        description="Manage the skills library catalog, categories, and placement.",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    subparsers.add_parser("catalog", help="Rebuild CATALOG.md")

    p_discover = subparsers.add_parser("discover", help="Search CATALOG.md")
    p_discover.add_argument("query", help="Search query")
    p_discover.add_argument("--limit", type=int, default=20, help="Maximum results")

    subparsers.add_parser("validate", help="Report validation issues")
    subparsers.add_parser("weed", help="Report duplicates and empty categories")
    subparsers.add_parser("repair", help="Apply safe mechanical repairs")

    p_move = subparsers.add_parser("move", help="Move a skill to a target category")
    p_move.add_argument("skill", help="Skill reference, e.g. category/skill-name")
    p_move.add_argument("target_category", help="Target category folder")

    p_new = subparsers.add_parser("new-category", help="Create category and DESCRIPTION.md")
    p_new.add_argument("name", help="Category folder name")
    p_new.add_argument("description", nargs="?", default=None, help="Category description")
    p_new.add_argument("--force", action="store_true", help="Overwrite DESCRIPTION.md")

    p_archive = subparsers.add_parser("archive", help="Archive a skill")
    p_archive.add_argument("skill", help="Skill reference, e.g. category/skill-name")

    args = parser.parse_args()

    commands = {
        "catalog": cmd_catalog,
        "discover": cmd_discover,
        "validate": cmd_validate,
        "weed": cmd_weed,
        "repair": cmd_repair,
        "move": cmd_move,
        "new-category": cmd_new_category,
        "archive": cmd_archive,
    }

    commands[args.command](args)


if __name__ == "__main__":
    main()
